ist_funktionen(name) AS (
  SELECT p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')'
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public'
    AND NOT EXISTS (
      SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e'
    )
),
abweichungen AS (
  SELECT 'FEHLT' AS befund, 'Spalte' AS art, name FROM erwartet_spalten
  EXCEPT ALL SELECT 'FEHLT', 'Spalte', name FROM ist_spalten
  UNION ALL
  SELECT 'EXTRA', 'Spalte', name FROM ist_spalten
  EXCEPT ALL SELECT 'EXTRA', 'Spalte', name FROM erwartet_spalten
  UNION ALL
  SELECT 'FEHLT', 'Funktion', name FROM erwartet_funktionen
  EXCEPT ALL SELECT 'FEHLT', 'Funktion', name FROM ist_funktionen
  UNION ALL
  SELECT 'EXTRA', 'Funktion', name FROM ist_funktionen
  EXCEPT ALL SELECT 'EXTRA', 'Funktion', name FROM erwartet_funktionen
)
SELECT befund, art, name FROM abweichungen
UNION ALL
SELECT 'OK', '', 'Alles deckungsgleich.'
WHERE NOT EXISTS (SELECT 1 FROM abweichungen)
ORDER BY 1, 2, 3;
